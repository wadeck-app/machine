// The job command ends with the first 12 hex digits of the sha256 of the script content (an argument the script ignores).
const hashOf = (content: string) => createHash('sha256').update(content).digest('hex').slice(0, 12);

// The Windows wrapper form of the orch job (spec: packaging.md section 6, 9.2a): a generated machine-daemon.vbs sets
// LAUNCHER_BUNDLE_OVERRIDE and runs the staged launcher, because orch.cmd cannot carry an environment variable.
// The orch is the stub, never the real one.

const CRLF = '\r\n';
const WSCRIPT = 'C:\\Windows\\System32\\wscript.exe';

describe('wrapperScript (golden template: the only text ever written, nothing typed by a user is interpreted)', () => {
  const exe = 'C:\\cfg\\bin\\1.0.0\\machine.exe';
  const bundle = 'C:\\opt\\lib\\machine.cjs';

  const template = (runCommand: string) =>
    [
      "' Generated by machine startup enable (do not edit: it is rewritten at every enable).",
      "' Sets LAUNCHER_BUNDLE_OVERRIDE for the launcher only, runs it hidden and waits for it, so orch supervises the job and restartOnExit sees its exit code.",
      'Option Explicit',
      'Dim shell, env, code',
      'Set shell = CreateObject("WScript.Shell")',
      'Set env = shell.Environment("Process")',
      `env("LAUNCHER_BUNDLE_OVERRIDE") = "${bundle}"`,
      `code = shell.Run(${runCommand}, 0, True)`,
      'WScript.Quit code',
      '',
    ].join(CRLF);

  it('exact content without --config-dir', () => {
    expect(wrapperScript({ exe, bundle })).toBe(template('"""C:\\cfg\\bin\\1.0.0\\machine.exe"" daemon"'));
  });

  it('exact content with --config-dir', () => {
    expect(wrapperScript({ exe, bundle, configDir: 'D:\\my cfg' })).toBe(template('"""C:\\cfg\\bin\\1.0.0\\machine.exe"" daemon --config-dir ""D:\\my cfg"""'));
  });

  it('is ASCII with CRLF line endings only', () => {
    const text = wrapperScript({ exe, bundle, configDir: 'D:\\c' });
    expect(/^[\x20-\x7e\r\n]*$/.test(text)).toBe(true);
    expect(text.replace(/\r\n/g, '')).not.toMatch(/[\r\n]/);
  });

  it('spaces, parentheses, apostrophes and ampersands are fine: no shell parses them inside the script', () => {
    const odd = "C:\\Users\\a b\\it's (x) & y\\machine.cjs";
    const text = wrapperScript({ exe: "C:\\a & b\\it's (1)\\machine.exe", bundle: odd });
    expect(text).toContain(`env("LAUNCHER_BUNDLE_OVERRIDE") = "${odd}"`);
    expect(text).toContain('"""C:\\a & b\\it\'s (1)\\machine.exe"" daemon"');
  });

  it.each([
    ['a double quote', 'C:\\a"b\\machine.cjs', /double quote/],
    ['a percent sign (Run expands %VAR%)', 'C:\\%TEMP%\\machine.cjs', /percent/],
    ['a newline', 'C:\\a\nb\\machine.cjs', /control character/],
    ['a tab', 'C:\\a\tb\\machine.cjs', /control character/],
    ['a non-ASCII character (wscript reads the file as ANSI)', 'C:\\caf\u00e9\\machine.cjs', /non-ASCII/],
    ['a relative path', 'machine.cjs', /absolute/],
  ])('refuses %s in the bundle path, naming the path and the fix', (_what, value, pattern) => {
    expect(() => wrapperScript({ exe, bundle: value })).toThrow(pattern);
    expect(() => wrapperScript({ exe, bundle: value })).toThrow(/move/);
  });

  it('applies the same refusals to the launcher and to the configuration folder', () => {
    expect(() => wrapperScript({ exe: 'C:\\a"b\\machine.exe', bundle })).toThrow(/double quote/);
    expect(() => wrapperScript({ exe, bundle, configDir: 'D:\\caf\u00e9' })).toThrow(/non-ASCII/);
    expect(() => wrapperScript({ exe, bundle, configDir: 'D:\\%X%' })).toThrow(/percent/);
  });
});

describe('daemonCommand: the wrapper job form on Windows', () => {
  const wrapper = { wscript: WSCRIPT, vbs: 'C:\\my cfg\\bin\\1.0.0\\machine-daemon.vbs', content: 'X' };
  const source: DaemonSource = { platform: 'win32', execPath: 'C:\\node.exe', scriptPath: 'C:\\nm\\machine.cjs', launcher: { exe: 'C:\\my cfg\\bin\\1.0.0\\machine.exe', bundleOverride: 'C:\\nm\\machine.cjs', wrapper } };

  it('is wscript.exe //B //Nologo "<vbs>" <content hash> with absolute paths; the configuration folder is inside the script, not in the command', () => {
    const expected = `"${WSCRIPT}" //B //Nologo "C:\\my cfg\\bin\\1.0.0\\machine-daemon.vbs" ${hashOf('X')}`;
    expect(daemonCommand(source)).toBe(expected);
    expect(daemonCommand(source, 'D:\\other')).toBe(expected);
  });

  it('a different script content gives a different command (so orch --restart-if-changed restarts the daemon when the bundle moves)', () => {
    const other = { ...source, launcher: { ...source.launcher!, wrapper: { ...wrapper, content: 'Y' } } };
    expect(daemonCommand(other)).not.toBe(daemonCommand(source));
    expect(daemonCommand(other)).toMatch(/machine-daemon\.vbs" [0-9a-f]{12}$/);
  });

  it('a percent or double quote in the script path is refused (cmd.exe), naming the fix', () => {
    expect(() => daemonCommand({ ...source, launcher: { ...source.launcher!, wrapper: { ...wrapper, vbs: 'C:\\%X%\\machine-daemon.vbs' } } })).toThrow(/%/);
  });

  it('without a wrapper the Windows override is still refused with the fix', () => {
    const bare: DaemonSource = { ...source, launcher: { exe: 'C:\\x\\machine.exe', bundleOverride: 'C:\\nm\\machine.cjs' } };
    expect(() => daemonCommand(bare)).toThrow(/cannot find the bundle/);
  });
});

describe('registeredForm: wrapper', () => {
  it('recognises wscript running machine-daemon.vbs, and nothing else run by wscript', () => {
    expect(registeredForm(`"${WSCRIPT}" //B //Nologo "C:\\c\\bin\\1\\machine-daemon.vbs" 0123456789ab`)).toBe('launcher-wrapper');
    expect(registeredForm(`"${WSCRIPT}" //B //Nologo "C:\\c\\bin\\1\\machine-daemon.vbs"`)).toBe('launcher-wrapper');
    expect(registeredForm(`"${WSCRIPT}" //B //Nologo "C:\\c\\bin\\1\\machine-daemon.vbs" rm -rf`)).toBe('unknown');
    expect(registeredForm(`"${WSCRIPT}" //B //Nologo "C:\\other.vbs"`)).toBe('unknown');
  });
});

describe('wrapper staging', () => {
  let root: string;
  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'machine-wrapper-'));
  });
  afterEach(() => rmSync(root, { recursive: true, force: true }));

  it('stageWrapper writes the content, replaces a different one, and wrapperState tells missing/current/different', () => {
    const file = join(root, 'bin', '1', 'machine-daemon.vbs');
    expect(wrapperState(file, 'A')).toBe('missing');
    stageWrapper(file, 'A');
    expect(readFileSync(file, 'utf8')).toBe('A');
    expect(wrapperState(file, 'A')).toBe('current');
    expect(wrapperState(file, 'B')).toBe('different');
    stageWrapper(file, 'B');
    expect(readFileSync(file, 'utf8')).toBe('B');
    expect(existsSync(`${file}.partial`)).toBe(false);
  });
});

// These stage into the real temp folder with Windows paths: only meaningful on a Windows host.
describe.runIf(process.platform === 'win32')('the wrapper form end to end through enable/status (stub orch, fake platform package)', () => {
  let root: string;
  let configDir: string;
  let stub: OrchStub;
  const BUNDLE = 'C:\\opt\\my lib\\machine.cjs';
  const notFound = (): string => {
    throw Object.assign(new Error('not found'), { code: 'MODULE_NOT_FOUND' });
  };
  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'machine-wrapper-e2e-'));
    configDir = join(root, 'config');
    mkdirSync(configDir);
    stub = makeOrchStub();
  });
  afterEach(() => {
    delete process.env.ORCH_STUB_WATCH;
    rmSync(root, { recursive: true, force: true });
    rmSync(stub.dir, { recursive: true, force: true });
  });
  const installed = (version = '1.0.0') => {
    const pkgDir = join(root, 'nm', ...platformPackageName('win32-x64').split('/'));
    mkdirSync(pkgDir, { recursive: true });
    writeFileSync(join(pkgDir, 'machine.exe'), 'LAUNCHER-BYTES');
    writeFileSync(join(pkgDir, 'package.json'), JSON.stringify({ name: 'x', version }));
    return (spec: string) => {
      const target = join(root, 'nm', ...spec.split('/'));
      if (!existsSync(target)) return notFound();
      return target;
    };
  };
  const ctxWith = (resolve: (s: string) => string, extra: Partial<StartupContext> = {}): StartupContext => ({
    configDir,
    orch: stub.orch,
    // The wrapper script and its staging order are under test here, not the start of the daemon (startupDaemon.test.ts).
    start: false,
    platform: 'win32',
    // No node on PATH: the launcher cannot find the bundle by itself, so the wrapper form is needed.
    env: { PATH: '', SystemRoot: 'C:\\Windows' },
    bundlePath: BUNDLE,
    binary: { platform: 'win32', arch: 'x64', resolve },
    ...extra,
  });
  const dirOf = (stamp: string) => join(configDir, 'bin', stamp);
  const vbsOf = (stamp: string) => join(dirOf(stamp), 'machine-daemon.vbs');
  const contentOf = (stamp: string, bundle = BUNDLE) => wrapperScript({ exe: join(dirOf(stamp), 'machine.exe'), bundle, configDir });
  const commandOf = (stamp: string, bundle = BUNDLE) => `"${WSCRIPT}" //B //Nologo "${vbsOf(stamp)}" ${hashOf(contentOf(stamp, bundle))}`;
  const ensureArgs = (command: string) => ['ensure', 'startup', 'machine', '--command', command, '--restart-on-exit', '--timeout', '0', '--restart-if-changed', '--liveness-strategy', 'portFile', '--liveness-port-file', join(configDir, 'daemon.port.json'), '--json'];

  it('enable stages machine-daemon.vbs next to the launcher and registers wscript on it', async () => {
    stub.script({ ensure: { stdout: 'added machine\n' } });
    const r = await enableStartup(ctxWith(installed()));
    expect(stub.calls()).toEqual([ensureArgs(commandOf('1.0.0'))]);
    expect(readFileSync(vbsOf('1.0.0'), 'utf8')).toBe(contentOf('1.0.0'));
    expect(r).toMatchObject({ action: 'added', form: 'launcher-wrapper', command: commandOf('1.0.0') });
  });

  it('the script is staged BEFORE orch is called (a failing orch leaves it for the retry) and older stamps are pruned only after success', async () => {
    mkdirSync(dirOf('0.9.0'), { recursive: true });
    writeFileSync(vbsOf('0.9.0'), 'OLD');
    stub.script({ ensure: { code: 1, stderr: 'boom' } });
    await expect(enableStartup(ctxWith(installed()))).rejects.toThrow(StartupError);
    expect(existsSync(vbsOf('1.0.0'))).toBe(true);
    expect(existsSync(vbsOf('0.9.0'))).toBe(true);
    stub.script({ ensure: { stdout: 'updated machine\n' } });
    process.env.ORCH_STUB_WATCH = vbsOf('0.9.0');
    const r = await enableStartup(ctxWith(installed()));
    expect(stub.watched()).toEqual(['exists']);
    expect(existsSync(vbsOf('0.9.0'))).toBe(false);
    expect(existsSync(vbsOf('1.0.0'))).toBe(true);
    expect(r.pruned).toEqual({ removed: ['0.9.0'], skipped: [] });
  });

  it('a moved bundle changes the job command (same script path), so orch updates the job and restarts the daemon', async () => {
    stub.script({ ensure: { stdout: 'added machine\n' } });
    await enableStartup(ctxWith(installed()));
    stub.script({ ensure: { stdout: 'updated machine\n' } });
    const moved = 'C:\\elsewhere\\machine.cjs';
    const r = await enableStartup(ctxWith(installed(), { bundlePath: moved }));
    expect(r.command).toBe(commandOf('1.0.0', moved));
    expect(r.command).not.toBe(commandOf('1.0.0'));
    expect(r.command.startsWith(`"${WSCRIPT}" //B //Nologo "${vbsOf('1.0.0')}" `)).toBe(true);
  });

  it('a bundle the launcher finds by itself keeps the plain launcher form: no script', async () => {
    const nodeDir = join(root, 'nodehome');
    mkdirSync(join(nodeDir, 'node_modules', '@wadeck-app', 'machine-cli'), { recursive: true });
    writeFileSync(join(nodeDir, 'node.exe'), '');
    const bundle = join(nodeDir, 'node_modules', '@wadeck-app', 'machine-cli', 'machine.cjs');
    writeFileSync(bundle, '');
    stub.script({ ensure: { stdout: 'added machine\n' } });
    const r = await enableStartup(ctxWith(installed(), { bundlePath: bundle, env: { PATH: nodeDir, PATHEXT: '.EXE', SystemRoot: 'C:\\Windows' } }));
    expect(r.form).toBe('launcher');
    expect(existsSync(vbsOf('1.0.0'))).toBe(false);
  });

  it.each([{ PATH: '' }, { PATH: '', SystemRoot: 'relative' }])('no usable %j SystemRoot: refused loudly, nothing registered', async (env) => {
    await expect(enableStartup(ctxWith(installed(), { env }))).rejects.toThrow(/SystemRoot/);
    expect(stub.calls()).toEqual([]);
  });

  it('a non-ASCII bundle path is refused loudly with the fix, nothing registered', async () => {
    await expect(enableStartup(ctxWith(installed(), { bundlePath: 'C:\\caf\u00e9\\machine.cjs' }))).rejects.toThrow(/non-ASCII.*move/s);
    expect(stub.calls()).toEqual([]);
  });

  it('status expects the wrapper command without writing anything; current script and command: up to date, form reported', async () => {
    stub.script({ list: { stdout: '[]' }, show: { code: 3 } });
    const absent = await startupStatus(ctxWith(installed()));
    expect(absent).toMatchObject({ exists: false, expected: commandOf('1.0.0'), expectedForm: 'launcher-wrapper' });
    expect(existsSync(join(configDir, 'bin'))).toBe(false);

    stub.script({ ensure: { stdout: 'added machine\n' } });
    await enableStartup(ctxWith(installed()));
    stub.script({ list: { stdout: '[]' }, show: { stdout: JSON.stringify({ command: commandOf('1.0.0') }) } });
    expect(await startupStatus(ctxWith(installed()))).toMatchObject({ upToDate: true, registeredForm: 'launcher-wrapper', expectedForm: 'launcher-wrapper', wrapper: 'current' });
  });

  it('status: the same command but a script that differs (bundle moved) or is missing is outdated', async () => {
    stub.script({ ensure: { stdout: 'added machine\n' } });
    await enableStartup(ctxWith(installed()));
    stub.script({ list: { stdout: '[]' }, show: { stdout: JSON.stringify({ command: commandOf('1.0.0') }) } });
    writeFileSync(vbsOf('1.0.0'), 'edited');
    expect(await startupStatus(ctxWith(installed()))).toMatchObject({ upToDate: false, wrapper: 'different' });
    rmSync(vbsOf('1.0.0'));
    expect(await startupStatus(ctxWith(installed()))).toMatchObject({ upToDate: false, wrapper: 'missing' });
  });

  it('status: a plain launcher or development job registered while the wrapper is expected is outdated and says both forms', async () => {
    stub.script({ list: { stdout: '[]' }, show: { stdout: JSON.stringify({ command: `"${join(dirOf('1.0.0'), 'machine.exe')}" daemon` }) } });
    expect(await startupStatus(ctxWith(installed()))).toMatchObject({ upToDate: false, registeredForm: 'launcher', expectedForm: 'launcher-wrapper' });
  });

  it('CLI enable and status name the wrapper form', async () => {
    stub.script({ ensure: { stdout: 'added machine\n' } });
    const en = await cli(configDir, ['startup', 'enable'], undefined, { startup: ctxWith(installed()) });
    expect(en.code, en.err).toBe(0);
    expect(en.out).toMatch(/form: staged launcher through a wscript wrapper/);
    expect(en.out).toContain('Node >= 24');
    stub.script({ list: { stdout: '[]' }, show: { stdout: JSON.stringify({ command: commandOf('1.0.0') }) } });
    const st = await cli(configDir, ['startup', 'status'], undefined, { startup: ctxWith(installed()) });
    expect(st.out).toMatch(/registered form: staged launcher through a wscript wrapper/);
    expect(st.out).toMatch(/up to date/);
    writeFileSync(vbsOf('1.0.0'), 'edited');
    const old = await cli(configDir, ['startup', 'status'], undefined, { startup: ctxWith(installed()) });
    expect(old.out).toMatch(/wrapper script: different/);
    expect(old.out).toMatch(/outdated: run machine startup enable/);
  });
});

// Real Windows Script Host, once each, hidden, a few hundred ms: fails loudly when wscript.exe is missing. Not run on other systems.
describe.runIf(process.platform === 'win32')('real wscript run', () => {
  let root: string;
  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), "machine wrapper 'real' (1)-"));
  });
  afterEach(() => rmSync(root, { recursive: true, force: true }));

  const runWscript = (vbs: string) => {
    if (!existsSync(WSCRIPT)) throw new Error(`${WSCRIPT} is missing: this test needs the Windows Script Host`);
    return spawnSync(WSCRIPT, ['//B', '//Nologo', vbs], { windowsHide: true, shell: false, timeout: 30_000 });
  };

  it('WScript.Quit propagates the exit code of a hidden, awaited child (cmd /c exit 7)', () => {
    const vbs = join(root, 'exit7.vbs');
    writeFileSync(vbs, ['Dim shell', 'Set shell = CreateObject("WScript.Shell")', 'WScript.Quit shell.Run("cmd /c exit 7", 0, True)', ''].join(CRLF));
    const r = runWscript(vbs);
    expect(r.error).toBeUndefined();
    expect(r.status).toBe(7);
  });

  it('the generated wrapper hands the override to the launcher only, passes daemon and --config-dir, and exits with its code', () => {
    const out = join(root, 'out.txt');
    const exe = join(root, 'machine.cmd');
    // A stand-in launcher: records the override and its arguments, exits 9.
    writeFileSync(exe, [`@echo %LAUNCHER_BUNDLE_OVERRIDE%^|%*> "${out}"`, '@exit /b 9', ''].join(CRLF));
    const bundle = join(root, 'my bundle (1)', 'machine.cjs');
    const vbs = join(root, 'machine-daemon.vbs');
    writeFileSync(vbs, wrapperScript({ exe, bundle, configDir: join(root, 'cfg dir') }));
    const before = process.env.LAUNCHER_BUNDLE_OVERRIDE;
    const r = runWscript(vbs);
    expect(r.error).toBeUndefined();
    expect(r.status).toBe(9);
    expect(readFileSync(out, 'utf8').trim()).toBe(`${bundle}|daemon --config-dir "${join(root, 'cfg dir')}"`);
    // The variable never reaches this (parent) process.
    expect(process.env.LAUNCHER_BUNDLE_OVERRIDE).toBe(before);
  });
});
